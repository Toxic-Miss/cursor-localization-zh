import json
import os

def load_dictionary(path):
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def save_dictionary(data, path):
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

def get_existing_entries(sections):
    """获取已存在的所有英文词条"""
    existing = set()
    for section in sections:
        for entry in section.get('entries', []):
            if len(entry) >= 1 and entry[0]:
                existing.add(entry[0].strip())
    return existing

def add_section_if_not_exists(sections, new_section):
    """添加新的 section（如果不存在）"""
    section_id = new_section['id']
    for i, s in enumerate(sections):
        if s.get('id') == section_id:
            # 合并 entries，去重
            existing_keys = set()
            for e in sections[i].get('entries', []):
                if e:
                    existing_keys.add(e[0])
            new_entries = []
            for e in new_section.get('entries', []):
                if e and len(e) >= 2 and e[0] not in existing_keys:
                    new_entries.append(e)
            if new_entries:
                sections[i]['entries'].extend(new_entries)
                print(f"  合并 {len(new_entries)} 条新词条到 section '{section_id}'")
            else:
                print(f"  section '{section_id}' 已存在，无新词条添加")
            return
    sections.append(new_section)
    print(f"  新增 section '{section_id}'，含 {len(new_section.get('entries', []))} 条词条")

